def pick_quotes(count: int, seed: int | None = None) -> list[str]:
    """取 ``count`` 条短语，尽量互不重复。

    - ``count <= len(QUOTES)``：随机打乱后顺序取用，保证不重复；
    - ``count`` 超过词库总量：循环补足（整体仍尽量分散）。
    """
    if count <= 0:
        return []
    pool = list(QUOTES)
    if not pool:
        return []
    rng = random.Random(seed)
    rng.shuffle(pool)
    if count <= len(pool):
        return pool[:count]
    out: list[str] = []
    while len(out) < count:
        rng.shuffle(pool)
        out.extend(pool)
    return out[:count]
